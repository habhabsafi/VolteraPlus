CREATE TABLE categories (
  id VARCHAR(60) PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0
) CHARACTER SET utf8mb4;

CREATE TABLE site_settings (
  id TINYINT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  tagline VARCHAR(255) NOT NULL,
  owner VARCHAR(150) NOT NULL,
  title VARCHAR(150) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(190) NOT NULL,
  web VARCHAR(190) NOT NULL,
  area VARCHAR(255) NOT NULL
) CHARACTER SET utf8mb4;

CREATE TABLE services (
  id VARCHAR(100) PRIMARY KEY,
  cat VARCHAR(60) NOT NULL,
  name VARCHAR(190) NOT NULL,
  img VARCHAR(190) NOT NULL,
  short VARCHAR(500) NOT NULL,
  why TEXT NOT NULL,
  perks LONGTEXT NOT NULL,
  hub LONGTEXT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  featured_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  KEY idx_services_cat (cat),
  CONSTRAINT fk_services_cat FOREIGN KEY (cat) REFERENCES categories(id)
) CHARACTER SET utf8mb4;

CREATE TABLE reviews (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(190) NOT NULL,
  body TEXT NOT NULL,
  name VARCHAR(150) NOT NULL,
  role VARCHAR(150) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1
) CHARACTER SET utf8mb4;

CREATE TABLE posts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  img VARCHAR(190) NOT NULL,
  cta VARCHAR(80) NOT NULL,
  short VARCHAR(500) NOT NULL,
  sections LONGTEXT NOT NULL,
  published_at DATE NOT NULL,
  published TINYINT(1) NOT NULL DEFAULT 1
) CHARACTER SET utf8mb4;
